import argparse
import json
import pathlib
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
RECIPES = ROOT / "recipes"
RAW = "https://raw.githubusercontent.com/Fibery-inc/process-cookbook/main/"
NOTE = "<!-- Generated by scripts/build_index.py from the recipe headers; edit the recipes, not this file. -->"
START, END = "<!-- recipes:start -->", "<!-- recipes:end -->"
LABELS = {"hr": "HR"}


def label(domain):
    return LABELS.get(domain, domain.capitalize())


def cell(text):
    return str(text).replace("|", "\\|")


def load():
    out = []
    for path in sorted(RECIPES.glob("*/*.md")):
        if path.name == "README.md":
            continue
        meta = yaml.safe_load(path.read_text(encoding="utf-8").split("---", 2)[1])
        rel = path.relative_to(ROOT).as_posix()
        out.append({"id": path.stem, "title": meta["title"], "summary": meta["summary"], "domain": meta["domain"],
                    "for": meta["for"], "keywords": meta["keywords"], "version": meta["version"],
                    "path": rel, "raw": RAW + rel})
    return sorted(out, key=lambda r: (r["domain"], r["title"].lower()))


def outputs(recipes):
    files = {ROOT / "index.json": json.dumps({"recipes": recipes}, indent=2, ensure_ascii=False) + "\n"}
    by_domain = {}
    for r in recipes:
        by_domain.setdefault(r["domain"], []).append(r)
    for domain, items in by_domain.items():
        rows = "\n".join(f"| [{cell(r['title'])}]({r['id']}.md) | {r['for']} | {cell(r['summary'])} |" for r in items)
        count = f"{len(items)} recipe" + ("" if len(items) == 1 else "s")
        files[RECIPES / domain / "README.md"] = (
            f"{NOTE}\n\n# {label(domain)}\n\n{count}.\n\n| Recipe | For | What it is |\n|---|---|---|\n{rows}\n")
    readme = (ROOT / "README.md").read_text(encoding="utf-8")
    if START not in readme or END not in readme:
        sys.exit(f"README.md needs the {START} and {END} markers")
    rows = []
    for domain, items in by_domain.items():
        if len(items) <= 5:
            shown = ", ".join(f"[{cell(r['title'])}](recipes/{domain}/{r['id']}.md)" for r in items)
        else:
            shown = f"{len(items)} recipes"
        rows.append(f"| [{label(domain)}](recipes/{domain}/) | {shown} |")
    table = (f"{len(recipes)} recipes in {len(by_domain)} domains.\n\n| Domain | Recipes |\n|---|---|\n"
             + "\n".join(rows))
    head, rest = readme.split(START, 1)
    files[ROOT / "README.md"] = f"{head}{START}\n{table}\n{END}{rest.split(END, 1)[1]}"
    return files, set(by_domain)


def main():
    parser = argparse.ArgumentParser(description="Rebuild index.json, the domain lists and the README table.")
    parser.add_argument("--check", action="store_true", help="fail when a generated file is out of date, without writing")
    args = parser.parse_args()
    files, used = outputs(load())
    leftover = [p for p in RECIPES.glob("*/README.md") if p.parent.name not in used]
    stale = [p for p, text in files.items() if not p.exists() or p.read_text(encoding="utf-8") != text] + leftover
    if args.check:
        for p in stale:
            print(f"{p.relative_to(ROOT)} is out of date: run python scripts/build_index.py")
        sys.exit(1 if stale else 0)
    for p, text in files.items():
        p.write_text(text, encoding="utf-8")
    for p in leftover:
        p.unlink()
    print(f"{len(stale)} files updated")


if __name__ == "__main__":
    main()
